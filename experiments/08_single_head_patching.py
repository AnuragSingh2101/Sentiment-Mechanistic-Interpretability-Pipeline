"""
Phase 6 — Single-Head Activation Patching
==========================================

Mechanistic Interpretability Project

Purpose
-------
Test whether individual GPT-2-small attention heads causally contribute
to the behavioral difference between clean and corrupted sentiment inputs.

For each of the 20 clean/corrupted sentiment pairs:

    1. Run the clean prompt.
    2. Run the corrupted prompt.
    3. Record clean and corrupted logit differences.
    4. Select ONE attention head.
    5. Replace that head's activation at the final sequence position
       in the corrupted run with the corresponding clean activation.
    6. Run the model forward.
    7. Measure the patched logit difference.
    8. Calculate normalized behavioral recovery.

GPT-2-small:
    Layers              = 12
    Attention heads     = 12 per layer
    Total heads         = 144
    Head dimension      = 64
    Hidden dimension    = 768

Primary metric
--------------
    LD = logit(" positive") - logit(" negative")

Recovery
--------
    recovery =
        (patched_LD - corrupted_LD)
        /
        (clean_LD - corrupted_LD)

Interpretation
--------------
    0.0  = no recovery
    0.5  = 50% recovery
    1.0  = complete recovery
    >1.0 = overshoot
    <0.0  = movement away from clean behavior

Important
---------
    - No model weights are modified.
    - No training occurs.
    - No gradients are required.
    - Only one head is patched at a time.
    - Only the final sequence position is patched.
    - Other heads remain unchanged.
    - Other sequence positions remain unchanged.

Phase 5 cache format
--------------------
The activation cache generated by:

    experiments/07_cache_activations.py

stores activations approximately as:

    cache["activation"][layer]

where each layer contains:

    Tensor shape = [12, 64]

Therefore this script explicitly extracts:

    cache["activation"][layer]

before performing the patch.

Outputs
-------
    results/patching/single_head_results.csv
    results/patching/head_ranking.csv
    results/patching/patching_summary.json
"""

