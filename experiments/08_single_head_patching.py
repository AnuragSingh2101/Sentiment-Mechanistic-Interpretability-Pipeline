# ============================================================================
# TOKENIZATION
# ============================================================================


def get_single_token_id(
    bridge: TransformerBridge,
    text: str,
) -> int:
    """
    Convert a token string into a single GPT-2 token ID.
    """

    token_ids = bridge.to_tokens(
        text,
        prepend_bos=False,
    )

    if token_ids.ndim == 2:
        token_ids = token_ids[0]

    if len(token_ids) != 1:
        raise ValueError(
            f"{text!r} does not tokenize to exactly one token.\n"
            f"Token IDs: {token_ids.tolist()}"
        )

    return int(token_ids[0].item())


# ============================================================================
# LOGIT DIFFERENCE
# ============================================================================


def get_logit_difference_from_logits(
    logits: torch.Tensor,
    positive_id: int,
    negative_id: int,
) -> float:
    """
    Calculate:

        logit(" positive") - logit(" negative")

    at the final sequence position.
    """

    final_logits = logits[0, -1]

    positive_logit = final_logits[positive_id]
    negative_logit = final_logits[negative_id]

    return float(
        (
            positive_logit
            - negative_logit
        ).item()
    )


# ============================================================================
# NORMAL FORWARD PASS
# ============================================================================


def run_model(
    bridge: TransformerBridge,
    prompt: str,
) -> float:
    """
    Run the model normally and return the logit difference.
    """

    if POSITIVE_ID is None or NEGATIVE_ID is None:
        raise RuntimeError(
            "Sentiment token IDs have not been initialized."
        )

    tokens = bridge.to_tokens(
        prompt,
        prepend_bos=True,
    )

    tokens = tokens.to(bridge.cfg.device)

    with torch.no_grad():
        logits = bridge(tokens)

    ld = get_logit_difference_from_logits(
        logits,
        POSITIVE_ID,
        NEGATIVE_ID,
    )

    del tokens
    del logits

    return ld


# ============================================================================
# CACHE LOADING
# ============================================================================


def load_cached_activation(
    path: Path,
) -> dict:
    """
    Load a Phase 5 activation cache.

    weights_only=False is intentional because the cache is a Python
    dictionary containing tensors and metadata.
    """

    if not path.exists():
        raise FileNotFoundError(
            f"\nActivation cache not found:\n{path}\n\n"
            "Run:\n"
            "python experiments/07_cache_activations.py"
        )

    cache = torch.load(
        path,
        map_location="cpu",
        weights_only=False,
    )

    if not isinstance(cache, dict):
        raise TypeError(
            f"Expected cache to be a dict, "
            f"got {type(cache)}"
        )

    if "activation" not in cache:
        raise KeyError(
            f"Cache does not contain 'activation'. "
            f"Available keys: {list(cache.keys())}"
        )

    return cache


# ============================================================================
# EXTRACT LAYER ACTIVATION
# ============================================================================


def extract_layer_activation(
    cache: dict,
    layer: int,
) -> torch.Tensor:
    """
    Extract one layer's activation from the Phase 5 cache.

    Expected cache structure:

        cache
        └── activation
            ├── 0 -> Tensor [12, 64]
            ├── 1 -> Tensor [12, 64]
            ├── ...
            └── 11 -> Tensor [12, 64]
    """

    activation_store = cache["activation"]

    if not isinstance(activation_store, dict):
        raise TypeError(
            "Expected cache['activation'] to be a dict, "
            f"got {type(activation_store)}"
        )

    # Normal case: integer layer keys.
    if layer in activation_store:
        activation = activation_store[layer]

    # Defensive support for string layer keys.
    elif str(layer) in activation_store:
        activation = activation_store[str(layer)]

    else:
        raise KeyError(
            f"Layer {layer} not found in activation cache.\n"
            f"Available layers: {list(activation_store.keys())}"
        )

    if not isinstance(activation, torch.Tensor):
        raise TypeError(
            f"Layer {layer} activation must be a torch.Tensor, "
            f"got {type(activation)}"
        )

    expected_shape = (
        N_HEADS,
        D_HEAD,
    )

    if tuple(activation.shape) != expected_shape:
        raise ValueError(
            f"Unexpected activation shape for layer {layer}: "
            f"{tuple(activation.shape)}\n"
            f"Expected: {expected_shape}"
        )

    return activation


# ============================================================================
# PATCH HOOK
# ============================================================================


def make_patch_hook(
    layer: int,
    head: int,
    clean_activation: torch.Tensor,
):
    """
    Create a hook that replaces exactly one attention head at the
    final sequence position.

    TransformerLens hook_z shape:

        [batch, sequence, heads, d_head]

    Cached activation shape:

        [heads, d_head]

    Only this element is replaced:

        activation[:, -1, head, :]
    """

    if not isinstance(
        clean_activation,
        torch.Tensor,
    ):
        raise TypeError(
            "clean_activation must be a torch.Tensor."
        )

    expected_shape = (
        N_HEADS,
        D_HEAD,
    )

    if tuple(clean_activation.shape) != expected_shape:
        raise ValueError(
            f"Expected clean activation shape "
            f"{expected_shape}, "
            f"got {tuple(clean_activation.shape)}"
        )

    hook_name = (
        f"blocks.{layer}.attn.hook_z"
    )

    clean_head = (
        clean_activation[head]
        .detach()
        .clone()
    )

    def patch_hook(
        activation: torch.Tensor,
        hook,
    ) -> torch.Tensor:
        """
        Patch only one head at the final token position.
        """

        if activation.ndim != 4:
            raise RuntimeError(
                "Unexpected hook_z activation rank.\n"
                f"Expected 4 dimensions, "
                f"got {activation.ndim}\n"
                f"Shape: {tuple(activation.shape)}"
            )

        batch_size = activation.shape[0]
        sequence_length = activation.shape[1]
        n_heads = activation.shape[2]
        d_head = activation.shape[3]

        if n_heads != N_HEADS:
            raise RuntimeError(
                f"Expected {N_HEADS} heads, "
                f"got {n_heads}"
            )

        if d_head != D_HEAD:
            raise RuntimeError(
                f"Expected d_head={D_HEAD}, "
                f"got {d_head}"
            )

        if sequence_length < 1:
            raise RuntimeError(
                "Sequence length must be at least 1."
            )

        patched = activation.clone()

        replacement = (
            clean_head
            .to(
                device=activation.device,
                dtype=activation.dtype,
            )
            .view(1, D_HEAD)
        )

        # Broadcast across batch.
        patched[
            :,
            -1,
            head,
            :,
        ] = replacement

        return patched

    return hook_name, patch_hook


# ============================================================================
# SINGLE HEAD PATCH
# ============================================================================


def run_single_patch(
    bridge: TransformerBridge,
    prompt: str,
    layer: int,
    head: int,
    clean_activation,
) -> float:
    """
    Run the corrupted prompt while replacing one attention head.

    clean_activation can be either:

        1. Full Phase 5 activation dictionary:
               cache["activation"]

       OR

        2. Direct layer tensor:
               cache["activation"][layer]

    The function automatically handles both.
    """

    # ----------------------------------------------------------------
    # If the complete activation dictionary was supplied, extract
    # the requested layer.
    # ----------------------------------------------------------------

    if isinstance(
        clean_activation,
        dict,
    ):
        clean_activation = extract_layer_activation(
            {
                "activation": clean_activation
            },
            layer,
        )

    # ----------------------------------------------------------------
    # Validate the resulting tensor.
    # ----------------------------------------------------------------

    if not isinstance(
        clean_activation,
        torch.Tensor,
    ):
        raise TypeError(
            "After layer extraction, "
            "clean_activation must be a torch.Tensor.\n"
            f"Got: {type(clean_activation)}"
        )

    expected_shape = (
        N_HEADS,
        D_HEAD,
    )

    if tuple(clean_activation.shape) != expected_shape:
        raise ValueError(
            f"Unexpected clean activation shape: "
            f"{tuple(clean_activation.shape)}\n"
            f"Expected: {expected_shape}"
        )

    # ----------------------------------------------------------------
    # Tokenize corrupted prompt.
    # ----------------------------------------------------------------

    tokens = bridge.to_tokens(
        prompt,
        prepend_bos=True,
    )

    tokens = tokens.to(
        bridge.cfg.device
    )

    # ----------------------------------------------------------------
    # Build patch hook.
    # ----------------------------------------------------------------

    hook_name, patch_hook = make_patch_hook(
        layer,
        head,
        clean_activation,
    )

    # ----------------------------------------------------------------
    # Forward pass with exactly one intervention.
    # ----------------------------------------------------------------

    with torch.no_grad():

        logits = bridge.run_with_hooks(
            tokens,
            fwd_hooks=[
                (
                    hook_name,
                    patch_hook,
                )
            ],
        )

    # ----------------------------------------------------------------
    # Calculate LD.
    # ----------------------------------------------------------------

    if POSITIVE_ID is None or NEGATIVE_ID is None:
        raise RuntimeError(
            "Sentiment token IDs have not been initialized."
        )

    patched_ld = (
        get_logit_difference_from_logits(
            logits,
            POSITIVE_ID,
            NEGATIVE_ID,
        )
    )

    # ----------------------------------------------------------------
    # Cleanup.
    # ----------------------------------------------------------------

    del tokens
    del logits

    return patched_ld


# ============================================================================
# RECOVERY
# ============================================================================


def calculate_recovery(
    clean_ld: float,
    corrupted_ld: float,
    patched_ld: float,
) -> float:
    """
    Calculate normalized behavioral recovery.

        recovery =
            (patched - corrupted)
            /
            (clean - corrupted)

    If clean and corrupted are effectively identical, the recovery
    is undefined and NaN is returned.
    """

    denominator = (
        clean_ld
        - corrupted_ld
    )

    if abs(denominator) < EPSILON:
        return float("nan")

    return (
        patched_ld
        - corrupted_ld
    ) / denominator


# ============================================================================
# HEAD LABEL
# ============================================================================


def head_label(
    layer: int,
    head: int,
) -> str:
    """
    Human-readable attention head identifier.
    """

    return f"L{layer}H{head}"


# ============================================================================
# VALIDATE CACHE
# ============================================================================


def validate_cache_structure(
    pair_id: int,
) -> None:
    """
    Validate both clean and corrupted caches for one pair.
    """

    clean_path = (
        CACHE_DIR
        / f"pair_{pair_id:02d}_clean.pt"
    )

    corrupted_path = (
        CACHE_DIR
        / f"pair_{pair_id:02d}_corrupted.pt"
    )

    clean_cache = load_cached_activation(
        clean_path
    )

    corrupted_cache = load_cached_activation(
        corrupted_path
    )

    for cache_name, cache in [
        ("clean", clean_cache),
        ("corrupted", corrupted_cache),
    ]:

        activation_store = cache["activation"]

        if not isinstance(
            activation_store,
            dict,
        ):
            raise TypeError(
                f"{cache_name} activation store "
                "must be a dictionary."
            )

        for layer in range(N_LAYERS):

            activation = extract_layer_activation(
                cache,
                layer,
            )

            if tuple(activation.shape) != (
                N_HEADS,
                D_HEAD,
            ):
                raise RuntimeError(
                    f"{cache_name} layer {layer} "
                    "has invalid shape."
                )

    del clean_cache
    del corrupted_cache

    gc.collect()


