def compare_single_vs_multi(
    phase6_df,
    phase7_df,
):

    print_header(
        "SINGLE-HEAD vs MULTI-HEAD COMPARISON"
    )

    if phase7_df is None:

        print(
            "Phase 7 quantitative results unavailable."
        )

        return pd.DataFrame()

    # ------------------------------------------------------------------------
    # Find Phase 6 recovery column
    # ------------------------------------------------------------------------

    phase6_candidates = (
        phase6_df[
            phase6_df[
                "head_label"
            ].isin(
                CANDIDATE_HEADS
            )
        ]
        .groupby(
            "head_label"
        )[
            "recovery"
        ]
        .mean()
    )

    # ------------------------------------------------------------------------
    # Find Phase 7 condition column
    # ------------------------------------------------------------------------

    condition_column = None

    for candidate in [
        "condition",
        "heads",
        "head_combination",
    ]:

        if candidate in phase7_df.columns:

            condition_column = candidate
            break

    if condition_column is None:

        return pd.DataFrame()

    # ------------------------------------------------------------------------
    # Find recovery
    # ------------------------------------------------------------------------

    if "recovery" not in phase7_df.columns:

        return pd.DataFrame()

    phase7_df = phase7_df.copy()

    rows = []

    for condition, group in phase7_df.groupby(
        condition_column
    ):

        values = (
            group[
                "recovery"
            ]
            .dropna()
            .to_numpy()
        )

        if len(values) == 0:
            continue

        rows.append(
            {
                "condition": condition,
                "mean_recovery": mean_or_nan(
                    values
                ),
                "median_recovery": median_or_nan(
                    values
                ),
                "n": len(values),
            }
        )

    multi_summary = pd.DataFrame(
        rows
    )

    if multi_summary.empty:

        return multi_summary

    # ------------------------------------------------------------------------
    # Best individual candidate
    # ------------------------------------------------------------------------

    best_single_head = (
        phase6_candidates
        .sort_values(
            ascending=False
        )
        .index[0]
    )

    best_single_value = float(
        phase6_candidates[
            best_single_head
        ]
    )

    # ------------------------------------------------------------------------
    # Best multi-head condition
    # ------------------------------------------------------------------------

    multi_only = (
        multi_summary[
            multi_summary[
                "condition"
            ]
            .astype(str)
            .str.contains(
                r"\+"
            )
        ]
        .sort_values(
            "mean_recovery",
            ascending=False,
        )
    )

    if multi_only.empty:

        print(
            "No multi-head conditions detected."
        )

        return multi_summary

    best_multi = (
        multi_only.iloc[0]
    )

    best_multi_value = float(
        best_multi[
            "mean_recovery"
        ]
    )

    absolute_improvement = (
        best_multi_value
        - best_single_value
    )

    relative_improvement = (
        absolute_improvement
        / abs(best_single_value)
        if best_single_value != 0
        else float("nan")
    )

    print(
        f"Best single head: "
        f"{best_single_head}"
    )

    print(
        f"Best single-head mean recovery: "
        f"{best_single_value:.6f}"
    )

    print(
        f"Best multi-head condition: "
        f"{best_multi['condition']}"
    )

    print(
        f"Best multi-head mean recovery: "
        f"{best_multi_value:.6f}"
    )

    print(
        f"Absolute improvement: "
        f"{absolute_improvement:+.6f}"
    )

    print(
        f"Relative improvement: "
        f"{relative_improvement * 100:+.2f}%"
        if math.isfinite(
            relative_improvement
        )
        else
        "Relative improvement: NaN"
    )

    comparison = pd.DataFrame(
        [
            {
                "best_single_head": best_single_head,
                "best_single_mean_recovery": best_single_value,
                "best_multi_condition": best_multi[
                    "condition"
                ],
                "best_multi_mean_recovery": best_multi_value,
                "absolute_improvement": absolute_improvement,
                "relative_improvement": relative_improvement,
            }
        ]
    )

    return comparison


