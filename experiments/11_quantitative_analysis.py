def pairwise_head_comparisons(
    phase6_df,
):

    print_header(
        "PAIRWISE CANDIDATE-HEAD COMPARISONS"
    )

    rows = []

    pivot = (
        phase6_df[
            phase6_df[
                "head_label"
            ].isin(
                CANDIDATE_HEADS
            )
        ]
        .pivot_table(
            index="pair_id",
            columns="head_label",
            values="recovery",
            aggfunc="mean",
        )
    )

    for i, head_a in enumerate(
        CANDIDATE_HEADS
    ):

        for head_b in CANDIDATE_HEADS[
            i + 1:
        ]:

            if (
                head_a not in pivot.columns
                or head_b not in pivot.columns
            ):
                continue

            x = pivot[
                head_a
            ].to_numpy()

            y = pivot[
                head_b
            ].to_numpy()

            mask = (
                np.isfinite(x)
                & np.isfinite(y)
            )

            x = x[mask]
            y = y[mask]

            if len(x) == 0:
                continue

            difference = (
                x - y
            )

            ci_low, ci_high = (
                confidence_interval_mean(
                    difference
                )
            )

            rows.append(
                {
                    "head_a": head_a,
                    "head_b": head_b,
                    "n_pairs": len(x),
                    "mean_a": mean_or_nan(x),
                    "mean_b": mean_or_nan(y),
                    "mean_difference_a_minus_b": mean_or_nan(
                        difference
                    ),
                    "median_difference": median_or_nan(
                        difference
                    ),
                    "ci95_low": ci_low,
                    "ci95_high": ci_high,
                    "paired_cohens_d": paired_cohens_d(
                        x,
                        y,
                    ),
                    "a_wins_fraction": float(
                        np.mean(
                            x > y
                        )
                    ),
                }
            )

    result = pd.DataFrame(
        rows
    )

    if not result.empty:

        print(
            result.to_string(
                index=False
            )
        )

    return result


