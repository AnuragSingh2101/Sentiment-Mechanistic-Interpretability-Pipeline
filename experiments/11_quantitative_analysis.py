def safe_numeric(
    df: pd.DataFrame,
    column: str,
):

    return pd.to_numeric(
        df[column],
        errors="coerce",
    )


def mean_or_nan(values):

    values = np.asarray(
        values,
        dtype=float,
    )

    values = values[
        np.isfinite(values)
    ]

    if len(values) == 0:
        return float("nan")

    return float(
        np.mean(values)
    )


def median_or_nan(values):

    values = np.asarray(
        values,
        dtype=float,
    )

    values = values[
        np.isfinite(values)
    ]

    if len(values) == 0:
        return float("nan")

    return float(
        np.median(values)
    )


def std_or_nan(values):

    values = np.asarray(
        values,
        dtype=float,
    )

    values = values[
        np.isfinite(values)
    ]

    if len(values) < 2:
        return float("nan")

    return float(
        np.std(
            values,
            ddof=1,
        )
    )


def standard_error(values):

    values = np.asarray(
        values,
        dtype=float,
    )

    values = values[
        np.isfinite(values)
    ]

    if len(values) < 2:
        return float("nan")

    return float(
        np.std(
            values,
            ddof=1,
        )
        / math.sqrt(len(values))
    )


def confidence_interval_mean(
    values,
    confidence=0.95,
):

    """
    Approximate two-sided confidence interval for the mean.

    Uses a t critical value when scipy is available.

    Falls back to the normal approximation otherwise.
    """

    values = np.asarray(
        values,
        dtype=float,
    )

    values = values[
        np.isfinite(values)
    ]

    n = len(values)

    if n < 2:

        return (
            float("nan"),
            float("nan"),
        )

    mean = np.mean(values)

    se = (
        np.std(
            values,
            ddof=1,
        )
        / math.sqrt(n)
    )

    try:

        from scipy.stats import t

        critical = t.ppf(
            1 - (1 - confidence) / 2,
            df=n - 1,
        )

    except Exception:

        critical = 1.96

    margin = (
        critical
        * se
    )

    return (
        float(mean - margin),
        float(mean + margin),
    )


def cohens_d_one_sample(
    values,
    baseline=0.0,
):

    """
    One-sample Cohen's d.

    Measures how far the observed recovery is from the
    zero-recovery baseline in standard-deviation units.
    """

    values = np.asarray(
        values,
        dtype=float,
    )

    values = values[
        np.isfinite(values)
    ]

    if len(values) < 2:
        return float("nan")

    sd = np.std(
        values,
        ddof=1,
    )

    if sd == 0:
        return float("nan")

    return float(
        (np.mean(values) - baseline)
        / sd
    )


def paired_cohens_d(
    x,
    y,
):

    """
    Paired-samples Cohen's d.

    Computes the standardized mean difference
    of x - y.
    """

    x = np.asarray(
        x,
        dtype=float,
    )

    y = np.asarray(
        y,
        dtype=float,
    )

    mask = (
        np.isfinite(x)
        & np.isfinite(y)
    )

    differences = (
        x[mask]
        - y[mask]
    )

    if len(differences) < 2:
        return float("nan")

    sd = np.std(
        differences,
        ddof=1,
    )

    if sd == 0:
        return float("nan")

    return float(
        np.mean(differences)
        / sd
    )


