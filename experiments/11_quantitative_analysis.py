def analyze_phase6():

    print_header(
        "PHASE 6 — SINGLE-HEAD QUANTITATIVE ANALYSIS"
    )

    require_file(
        PHASE6_RESULTS,
        "Phase 6 single-head results",
    )

    df = pd.read_csv(
        PHASE6_RESULTS
    )

    print(
        f"Rows loaded: {len(df)}"
    )

    print(
        "Columns:"
    )

    print(
        list(df.columns)
    )

    # ------------------------------------------------------------------------
    # Identify columns
    # ------------------------------------------------------------------------

    head_column = None

    for candidate in [
        "head_label",
        "head",
        "condition",
    ]:

        if candidate in df.columns:

            head_column = candidate
            break

    if head_column is None:

        raise ValueError(
            "Could not identify the Phase 6 head column."
        )

    recovery_column = None

    for candidate in [
        "recovery",
        "normalized_recovery",
        "recovery_fraction",
        "mean_recovery",
    ]:

        if candidate in df.columns:

            recovery_column = candidate
            break

    if recovery_column is None:

        raise ValueError(
            "Could not identify the Phase 6 recovery column."
        )

    df["head_label"] = (
        df[head_column]
        .astype(str)
        .str.strip()
    )

    df["recovery"] = safe_numeric(
        df,
        recovery_column,
    )

    # ------------------------------------------------------------------------
    # Candidate-head filter
    # ------------------------------------------------------------------------

    candidate_df = df[
        df["head_label"].isin(
            CANDIDATE_HEADS
        )
    ].copy()

    print(
        f"Candidate-head rows: "
        f"{len(candidate_df)}"
    )

    # ------------------------------------------------------------------------
    # Statistics
    # ------------------------------------------------------------------------

    rows = []

    for head in CANDIDATE_HEADS:

        subset = candidate_df[
            candidate_df[
                "head_label"
            ]
            == head
        ]

        values = (
            subset[
                "recovery"
            ]
            .dropna()
            .to_numpy()
        )

        n = len(values)

        mean = mean_or_nan(
            values
        )

        median = median_or_nan(
            values
        )

        sd = std_or_nan(
            values
        )

        se = standard_error(
            values
        )

        ci_low, ci_high = (
            confidence_interval_mean(
                values,
                CONFIDENCE_LEVEL,
            )
        )

        positive_fraction = (
            float(
                np.mean(
                    values > 0
                )
            )
            if n
            else float("nan")
        )

        d = cohens_d_one_sample(
            values
        )

        rows.append(
            {
                "head": head,
                "n": n,
                "mean_recovery": mean,
                "median_recovery": median,
                "std_recovery": sd,
                "standard_error": se,
                "ci95_low": ci_low,
                "ci95_high": ci_high,
                "positive_recovery_fraction": positive_fraction,
                "cohens_d_vs_zero": d,
            }
        )

    summary = pd.DataFrame(
        rows
    )

    print()
    print(
        summary.to_string(
            index=False
        )
    )

    return df, summary


